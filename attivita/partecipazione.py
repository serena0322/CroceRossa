"""Interfaccia Partecipazione (realizzata da Prenotazione e Iscrizione)."""
from abc import ABC, abstractmethod

class Partecipazione(ABC):
    @abstractmethod
    def getDatiVolontario(self) -> dict: ...
    @abstractmethod
    def liberaPosti(self) -> None: ...
    @abstractmethod
    def notificaEliminazione(self) -> None: ...
    @abstractmethod
    def avvisaModifica(self) -> None: ...
